  var currentLang = "fa";

  function t(key, vars) {
    vars = vars || {};
    var dict = STRINGS[currentLang] || STRINGS.en;
    var s = dict[key];
    if (s == null) s = (STRINGS.en[key] != null ? STRINGS.en[key] : key);
    for (var k in vars) {
      if (Object.prototype.hasOwnProperty.call(vars, k)) {
        s = String(s).split("{" + k + "}").join(String(vars[k]));
      }
    }
    return s;
  }

  function simpleExpl(ruleId, parts) {
    parts = parts || {};
    var id = ruleId || "";
    return {
      title: t("sx." + id + ".title", parts),
      why: t("sx." + id + ".why", parts),
      evidence: t("sx." + id + ".evidence", parts),
      fix: t("sx." + id + ".fix", parts)
    };
  }

  function getLang() { return currentLang; }

  function setLang(lang) {
    currentLang = lang === "fa" ? "fa" : "en";
    try { localStorage.setItem("ad_lang", currentLang); } catch (e) {}
    return currentLang;
  }

  function loadLang() {
    try {
      var saved = localStorage.getItem("ad_lang");
      if (saved === "fa" || saved === "en") currentLang = saved;
    } catch (e) {}
    return currentLang;
  }

  function applyI18n(root) {
    root = root || document;
    var nodes = root.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute("data-i18n");
      if (!key) continue;
      var val = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") el.placeholder = val;
      else if (el.tagName === "OPTION") el.textContent = val;
      else el.textContent = val;
    }
    var titles = root.querySelectorAll("[data-i18n-title]");
    for (var j = 0; j < titles.length; j++) {
      titles[j].title = t(titles[j].getAttribute("data-i18n-title"));
    }
    var ph = root.querySelectorAll("[data-i18n-placeholder]");
    for (var k = 0; k < ph.length; k++) {
      ph[k].placeholder = t(ph[k].getAttribute("data-i18n-placeholder"));
    }
  }

